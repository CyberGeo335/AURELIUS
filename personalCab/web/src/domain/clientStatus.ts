/** Public HTTP status copy shared by the home and application journey. */
export function httpClientStatus(app: Application) {
  if (app.server?.offer_stale)
    return {
      happening: 'Данные изменились. Требуется повторная проверка предложения.',
      next: 'Ожидайте повторного решения банка.',
    };
  const copy: Partial<Record<ReturnType<typeof displayStatus>, [string, string]>> = {
    DRAFT: [
      'Вы заполняете заявку.',
      'Продолжите заполнение, подтвердите сведения и отправьте заявку.',
    ],
    SUBMITTED: [
      'Заявка отправлена в банк.',
      'Ожидайте проверки. Если понадобятся сведения, запрос появится в заявке.',
    ],
    CHECKING: ['Банк проверяет заявку и сведения о бизнесе.', 'Ожидайте результата проверки.'],
    MANUAL_REVIEW: [
      'Заявку рассматривает специалист банка.',
      'Ожидайте решения. Следите за запросами в заявке.',
    ],
    NEEDS_INFO: [
      'Для продолжения рассмотрения нужны дополнительные сведения.',
      'Откройте заявку и ответьте на запрос банка.',
    ],
    OFFERED: [
      'Банк подготовил предложение с условиями.',
      'Откройте заявку, проверьте условия и примите предложение либо отклоните его с отменой заявки.',
    ],
    ACCEPTED: [
      'Предложение принято. Условия сохранены.',
      'Дополнительных действий в кабинете не требуется.',
    ],
    DECLINED: [
      'По заявке принято решение об отказе.',
      'Откройте заявку и ознакомьтесь с причиной отказа.',
    ],
    CANCELLED: ['Заявка отменена.', 'При необходимости создайте новую заявку.'],
  };
  const [happening, next] = copy[displayStatus(app)] ?? [
    'Статус заявки обновлён.',
    'Откройте заявку, чтобы посмотреть подробности.',
  ];
  return { happening, next };
}
