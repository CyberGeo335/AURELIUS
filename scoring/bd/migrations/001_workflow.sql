-- Additive workflow integration. Does not recreate or modify public business tables.
CREATE SCHEMA IF NOT EXISTS aurelius_workflow;
CREATE TABLE IF NOT EXISTS aurelius_workflow.credit_cases (
 case_id TEXT PRIMARY KEY, owner_id TEXT NOT NULL, borrower_id TEXT,
 status TEXT NOT NULL, version INTEGER NOT NULL, payload TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS aurelius_workflow.credit_sessions (
 owner_id TEXT NOT NULL, session_id TEXT NOT NULL,
 case_id TEXT NOT NULL REFERENCES aurelius_workflow.credit_cases(case_id),
 PRIMARY KEY(owner_id, session_id));
CREATE TABLE IF NOT EXISTS aurelius_workflow.credit_receipts (
 owner_id TEXT NOT NULL, session_id TEXT NOT NULL, message_id TEXT NOT NULL,
 input_hash TEXT NOT NULL, result TEXT NOT NULL, PRIMARY KEY(owner_id, session_id, message_id));
CREATE TABLE IF NOT EXISTS aurelius_workflow.credit_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, case_id TEXT NOT NULL REFERENCES aurelius_workflow.credit_cases(case_id),
 revision INTEGER, correlation_id TEXT, message_id TEXT, event_at TEXT, payload TEXT,
 UNIQUE(case_id, message_id, correlation_id));
CREATE TABLE IF NOT EXISTS aurelius_workflow.web_clients (
 token TEXT PRIMARY KEY, actor_id TEXT NOT NULL, session_id TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS aurelius_workflow.case_applications (
 case_id TEXT NOT NULL REFERENCES aurelius_workflow.credit_cases(case_id), revision INTEGER NOT NULL,
 product_code VARCHAR(10) NOT NULL REFERENCES public.credit_products(product_code),
 company_id BIGINT NOT NULL REFERENCES public.companies(company_id),
 application_id BIGINT NOT NULL UNIQUE REFERENCES public.credit_applications(application_id),
 snapshot_id BIGINT REFERENCES public.application_snapshots(snapshot_id), input_hash TEXT NOT NULL,
 PRIMARY KEY(case_id, revision, product_code));
